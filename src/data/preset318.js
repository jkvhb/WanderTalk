const CHECKED_AT = '2026-07-22'

function place(id, name, lng, lat, altitude, query, resultName, address, gcjLng, gcjLat, extra = {}) {
  return {
    placeId: id,
    name,
    lng,
    lat,
    ...(altitude == null ? {} : { altitude }),
    narrate: false,
    roles: ['route'],
    routeType: 'main',
    source: {
      provider: 'amap-web-service',
      coordinateSystem: 'WGS-84',
      checkedAt: CHECKED_AT,
      query,
      resultName,
      address,
      gcj02: { lng: gcjLng, lat: gcjLat },
    },
    ...extra,
  }
}

